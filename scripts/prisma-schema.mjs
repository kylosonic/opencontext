import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const provider = process.argv[2] ?? "postgresql";
if (!["postgresql", "sqlite"].includes(provider)) {
  throw new Error(`Unsupported Prisma provider: ${provider}`);
}

const sourcePath = path.join(repoRoot, "apps", "web", "prisma", "schema.prisma");
const outputDir =
  provider === "postgresql"
    ? path.join(repoRoot, "apps", "web", "prisma", "postgres")
    : path.join(repoRoot, "apps", "web", "prisma", ".generated");
const outputPath = path.join(outputDir, "schema.prisma");
const source = await readFile(sourcePath, "utf8");
const generated = source.replace(
  /provider\s*=\s*"(?:sqlite|postgresql)"/,
  `provider = "${provider}"`,
);
if (generated === source && provider !== "sqlite") {
  throw new Error("Could not replace the Prisma datasource provider");
}

await mkdir(outputDir, { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/prisma-schema.mjs. Do not edit directly.\n${generated}`,
  "utf8",
);
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${provider})`);
